"""Generate docs/RUN_COMMANDS.md: every command of the full benchmark, one per line.

Run from the repo root after adding a model or changing utils/hparams.py:
    python docs/make_run_commands.py
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, ROOT)

from utils.hparams import DATASETS, PAPER_EVALUATED, uses_paper_hparams  # noqa: E402

SEEDS = [123, 1234, 12345, 123456, 1234567]
RATIOS = [0.1, 0.2, 0.3, 0.4]
DATASET_LABEL = {'yelpchi': 'YelpChi', 'amazon': 'Amazon', 'tfinance': 'T-Finance',
                 'tsocial': 'T-Social', 'elliptic': 'Elliptic', 'comp': 'FDCompCN'}
GRAPHCONSIS_FILE = {'yelpchi': 'YelpChi.mat', 'amazon': 'Amazon.mat', 'tfinance': 'tfinance',
                    'tsocial': 'tsocial', 'elliptic': 'elliptic', 'comp': 'comp'}


def train_cmd(model, ds, ratio, seed):
    common = '--seed {} --train_ratio {} --gpu 0'.format(seed, ratio)
    if model == 'GraphConsis':
        return ('python algorithms/GraphConsis/supervised_train.py --train_prefix dataset/ '
                '--file_name {} --sigmoid --epochs 500 {}'.format(GRAPHCONSIS_FILE[ds], common))
    return 'python algorithms/{m}/{m}_main.py --dataset {d} --data_prefix dataset/ {c}'.format(
        m=model, d=ds, c=common)


def main():
    models = sorted(PAPER_EVALUATED)
    out = []
    w = out.append
    w('# Full benchmark command list')
    w('')
    w('Generated by `python docs/make_run_commands.py` (do not edit by hand). The procedure and '
      'one-shot loops are in the root `README.md` ("Running the Full Benchmark") and '
      '`docs/RUNPOD.md`.')
    w('')
    w('- Run every command from the **repo root** with the virtual environment active '
      '(`source .venv/bin/activate` on RunPod, `.venv\\Scripts\\activate` on Windows). '
      'Each command is a single line, so it works in bash and PowerShell.')
    w('- **Do not add hyperparameter flags** (`--learning_rate`, `--hid_dim`, ...): explicit flags '
      'override the paper / tuned values.')
    w('- Seeds: {}. Training ratios: {} (valid 20% and test 40% stay fixed).'.format(
        ', '.join(map(str, SEEDS)), ', '.join(str(r) for r in RATIOS)))
    w('- Outputs: `results/<Model>/<dataset>/seed<seed>_train<pct>/`. The folder name is built from '
      'the arguments, so no two commands below share a folder and running the list from top to '
      'bottom never overwrites anything (`config.json` records `train_ratio` and `hparam_source`).')
    w('- Limits per run: more than 4 hours stops the run and writes `OOT.txt` (exit code 124); more '
      'than 95 GB of GPU memory stops it and writes `OOM.txt` (exit code 125), both in the run folder. '
      'Skip a command whose folder already has `metrics.json`, `OOT.txt` or `OOM.txt`.')
    w('')
    n_tune = sum(1 for m in models for d in DATASETS if not uses_paper_hparams(m, d))
    n_train = len(models) * len(DATASETS) * len(RATIOS) * len(SEEDS)
    w('Totals: {} tuning commands (step 1), {} training commands (step 2), {} models.'.format(
        n_tune, n_train, len(models)))
    w('')

    w('## Step 1 - Hyperparameter tuning (pairs not evaluated in the original paper)')
    w('')
    w('Run once, before any training. Each command runs 20 trials x 5 seeds on the 40% split, ranks them by '
      'mean validation AUPRC and writes `configs/tuned/<Model>/<dataset>.json`; add `--resume` to continue an interrupted '
      'pair. Equivalent single command: `python tune_hparams.py --all --gpu 0`.')
    w('')
    for model in models:
        pairs = [d for d in DATASETS if not uses_paper_hparams(model, d)]
        if not pairs:
            continue
        w('### {}'.format(model))
        w('')
        w('```bash')
        for d in pairs:
            w('python tune_hparams.py --model {} --dataset {} --gpu 0'.format(model, d))
        w('```')
        w('')

    w('## Step 2 - Training: every model x dataset x training ratio x seed')
    w('')
    for model in models:
        w('### {}'.format(model))
        w('')
        for d in DATASETS:
            src = 'paper hyperparameters' if uses_paper_hparams(model, d) else 'tuned hyperparameters (step 1)'
            w('#### {} - {} ({})'.format(model, DATASET_LABEL[d], src))
            w('')
            w('```bash')
            for ratio in RATIOS:
                for seed in SEEDS:
                    w(train_cmd(model, d, ratio, seed))
            w('```')
            w('')

    path = os.path.join(ROOT, 'docs', 'RUN_COMMANDS.md')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote', os.path.relpath(path, ROOT), '({} tuning + {} training commands)'.format(n_tune, n_train))


if __name__ == '__main__':
    main()
